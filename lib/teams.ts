export const teams: Team[] = teamSeeds.map((team) => ({
  ...team,
  players: team.players.map((player) => {
    const [
      name,
      position,
      minutes,
      usage,
      scoring,
      efficiency,
      threePoint,
      playmaking,
      rebounding,
      defense,
      rimProtection,
      physicality,
      clutch,
    ] = player;

    return {
      id: `${team.id}-${name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "")}`,
      teamId: team.id,
      name,
      position,
      minutes,
      usage,
      scoring,
      efficiency,
      threePoint,
      playmaking,
      rebounding,
      defense,
      rimProtection,
      physicality,
      clutch,
    };
  }),
}));

export function getTeamById(id: string) {
  return teams.find((team) => team.id === id);
}

export function getTeamPair(teamAId: string, teamBId: string) {
  const teamA = getTeamById(teamAId);
  const teamB = getTeamById(teamBId);
  return teamA && teamB ? { teamA, teamB } : null;
}
